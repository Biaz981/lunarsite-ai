function exportReport(mission, score) {
    if (typeof window.jspdf === 'undefined') {
        alert('PDF library load nahi hui. Page refresh karein.');
        return;
    }
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF();
    const nasaBlue = [11, 61, 145];

    doc.setFillColor(...nasaBlue);
    doc.rect(0, 0, 210, 30, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(22);
    doc.setFont('helvetica', 'bold');
    doc.text('LunarSite AI Report', 15, 20);

    doc.setTextColor(0, 0, 0);
    doc.setFontSize(18);
    doc.text(mission.fullName || mission.name, 15, 50);

    const sc = score >= 85 ? [81,207,102] : score >= 70 ? [255,212,59] : score >= 55 ? [255,146,43] : [255,107,107];
    doc.setFillColor(...sc);
    doc.rect(15, 58, 60, 20, 'F');
    doc.setTextColor(0, 0, 0);
    doc.setFontSize(16);
    doc.text(`${score}/100`, 28, 72);
    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.text(getRecommendation(score), 80, 70);

    let y = 95;
    doc.setFontSize(14);
    doc.setFont('helvetica', 'bold');
    doc.text('Mission Details', 15, y);
    y += 10;
    doc.setFontSize(11);
    doc.setFont('helvetica', 'normal');

    const details = [
        ['Company', mission.company || 'N/A'],
        ['Lander', mission.lander || 'N/A'],
        ['Launch', mission.launch || 'N/A'],
        ['Landing Site', mission.site],
        ['Region', mission.region || mission.site],
        ['Coordinates', `${mission.lat.toFixed(4)}°, ${mission.lon.toFixed(4)}°`],
        ['Payload', mission.payload || 'N/A']
    ];
    details.forEach(([l, v]) => {
        doc.setFont('helvetica', 'bold');
        doc.text(l + ':', 15, y);
        doc.setFont('helvetica', 'normal');
        doc.text(String(v), 70, y);
        y += 8;
    });

    y += 5;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.text('Objective', 15, y);
    y += 8;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(11);
    const objLines = doc.splitTextToSize(mission.objective, 180);
    doc.text(objLines, 15, y);
    y += objLines.length * 6 + 10;

    if (!mission.era) {
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(14);
        doc.text('AI Score Breakdown', 15, y);
        y += 10;
        const m = SITE_METRICS[mission.id];
        const params = [
            ['Water Ice', m.waterIce, '35%'],
            ['Sunlight', m.sunlight, '25%'],
            ['Terrain', m.terrain, '25%'],
            ['Science', m.science, '15%']
        ];
        doc.setFontSize(11);
        params.forEach(([l, v, w]) => {
            doc.setFont('helvetica', 'normal');
            doc.text(`${l} (${w}):`, 15, y);
            doc.text(`${v}/100`, 100, y);
            doc.setFillColor(220,220,220);
            doc.rect(130, y - 4, 60, 5, 'F');
            doc.setFillColor(...nasaBlue);
            doc.rect(130, y - 4, 60 * (v/100), 5, 'F');
            y += 10;
        });
    }

    doc.setFontSize(9);
    doc.setTextColor(120,120,120);
    doc.text('Generated by LunarSite AI | Biaz Ahmad | NASA Space Apps 2026', 15, 285);
    doc.save(`LunarSite_${mission.name.replace(/\s/g,'_')}_Report.pdf`);
}